#!/usr/bin/env bash
# Install CUTOFF system-wide so `cutoff` works from any directory.
#
#   sudo ./tools/install-global.sh              # /opt/cutoff + /var/lib/cutoff + systemd
#   sudo ./tools/install-global.sh --no-start   # install only
#   sudo ./tools/install-global.sh --force      # upgrade over an existing install
#
# Environment overrides:
#   CUTOFF_PREFIX    install dir        (default /opt/cutoff)
#   CUTOFF_BIN_DIR   wrapper dir        (default /usr/local/bin)
#   CUTOFF_DATA_DIR  inventory + token  (default /var/lib/cutoff)
#   CUTOFF_PORT      listener port      (default 8848)
#   CUTOFF_SKIP_SYSTEMD=1               (install without a unit, for user-level tests)
set -euo pipefail

PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
PREFIX="${CUTOFF_PREFIX:-/opt/cutoff}"
BIN_DIR="${CUTOFF_BIN_DIR:-/usr/local/bin}"
DATA_DIR="${CUTOFF_DATA_DIR:-/var/lib/cutoff}"
PORT="${CUTOFF_PORT:-8848}"
UNIT="/etc/systemd/system/cutoff.service"
START=1
FORCE=0

for arg in "$@"; do
  case "$arg" in
    --no-start) START=0 ;;
    --force)    FORCE=1 ;;
    -h|--help)  sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

log()  { printf '[*] %s\n' "$*"; }
warn() { printf '[!] %s\n' "$*" >&2; }
die()  { printf '[x] %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight
[ -f "$PROJECT/backend/app.py" ] || die "run this from a CUTOFF checkout"
command -v python3 >/dev/null || die "python3 is required"
python3 -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' \
  || die "Python 3.10+ is required (found $(python3 -V 2>&1))"

if [ "$(id -u)" -ne 0 ] && [ -z "${CUTOFF_SKIP_SYSTEMD:-}" ] && [ "$PREFIX" = "/opt/cutoff" ]; then
  die "run as root: sudo $0"
fi
if [ -e "$PREFIX" ] && [ "$FORCE" -eq 0 ] && [ -f "$PREFIX/VERSION" ]; then
  die "$PREFIX already holds CUTOFF $(cat "$PREFIX/VERSION") — use --force to upgrade"
fi

if command -v ss >/dev/null 2>&1 && ss -ltn 2>/dev/null | grep -q ":${PORT} "; then
  warn "port ${PORT} is already in use — stop that instance or set CUTOFF_PORT"
fi

# ---------------------------------------------------------------- copy tree
log "installing to $PREFIX"
mkdir -p "$PREFIX"
if [ "$PROJECT" != "$PREFIX" ]; then
  tar -C "$PROJECT" -cf - \
      --exclude='./.venv' --exclude='./backend/data' --exclude='./.git' \
      --exclude='./**/__pycache__' --exclude='*.pyc' --exclude='./cutoff.log.legacy' \
      . | tar -C "$PREFIX" -xf -
fi
chmod +x "$PREFIX/run.sh" "$PREFIX/bin/cutoff" "$PREFIX"/tools/*.sh 2>/dev/null || true

# ---------------------------------------------------------------- venv
if [ ! -x "$PREFIX/.venv/bin/python" ] || [ "$FORCE" -eq 1 ]; then
  log "creating virtualenv"
  rm -rf "$PREFIX/.venv"
  python3 -m venv "$PREFIX/.venv"
  "$PREFIX/.venv/bin/python" -m pip install -q --upgrade pip >/dev/null 2>&1 || true
  log "installing python dependencies"
  "$PREFIX/.venv/bin/python" -m pip install -q -r "$PREFIX/backend/requirements.txt" \
    || die "pip install failed (needs network once, then it is offline-safe)"
fi
"$PREFIX/.venv/bin/python" -c 'import flask, waitress' \
  || die "installed venv is missing Flask/waitress"

if [ ! -x "$PREFIX/vendor/nmap/usr/bin/nmap" ] && [ ! -d "$PREFIX/vendor/nmap/win32" ]; then
  warn "vendor/ has no nmap/bettercap — run ./tools/fetch-vendor.sh for those consoles"
fi

# ---------------------------------------------------------------- data dir
log "data dir: $DATA_DIR (0700)"
mkdir -p "$DATA_DIR"
chmod 0700 "$DATA_DIR"
[ -f "$DATA_DIR/api_token" ] && chmod 0600 "$DATA_DIR/api_token" || true

# ---------------------------------------------------------------- CLI wrapper
log "command: $BIN_DIR/cutoff"
mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/cutoff" <<WRAPPER
#!/bin/sh
# generated by tools/install-global.sh — pins the install and data paths
CUTOFF_PREFIX="$PREFIX" CUTOFF_DATA_DIR="$DATA_DIR" \\
CUTOFF_PORT="\${CUTOFF_PORT:-$PORT}" CUTOFF_HOST="\${CUTOFF_HOST:-127.0.0.1}" \\
  exec "$PREFIX/bin/cutoff" "\$@"
WRAPPER
chmod 0755 "$BIN_DIR/cutoff"
ln -sf "$PREFIX/bin/cutoff" "$PREFIX/bin/cutoff-cli" 2>/dev/null || true

# ---------------------------------------------------------------- systemd
if [ -z "${CUTOFF_SKIP_SYSTEMD:-}" ] && [ -d /run/systemd/system ] && command -v systemctl >/dev/null && [ "$(id -u)" -eq 0 ]; then
  log "writing $UNIT"
  cat > "$UNIT" <<UNITEOF
[Unit]
Description=CUTOFF network device control console
Documentation=file://$PREFIX/README.md
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=root
Group=root
WorkingDirectory=$PREFIX
Environment=CUTOFF_HOST=127.0.0.1
Environment=CUTOFF_PORT=$PORT
Environment=CUTOFF_DATA_DIR=$DATA_DIR
Environment=CUTOFF_SIMULATE=auto
Environment=PYTHONDONTWRITEBYTECODE=1
ExecStart=$PREFIX/.venv/bin/python $PREFIX/backend/app.py
Restart=always
RestartSec=3
StartLimitBurst=5

UMask=0077
CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_RAW CAP_NET_BIND_SERVICE
ProtectSystem=strict
ReadWritePaths=$DATA_DIR
ProtectHome=read-only
PrivateTmp=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_PACKET AF_NETLINK
SystemCallArchitectures=native
SystemCallFilter=@system-service
StandardOutput=journal
StandardError=journal
SyslogIdentifier=cutoff
TimeoutStopSec=15

[Install]
WantedBy=multi-user.target
UNITEOF
  systemctl daemon-reload
  if [ "$START" -eq 1 ]; then
    log "starting the service"
    systemctl enable --now cutoff.service
    sleep 1
    systemctl --no-pager --lines=3 status cutoff.service || true
  else
    systemctl enable cutoff.service >/dev/null 2>&1 || true
  fi
elif [ -n "${CUTOFF_SKIP_SYSTEMD:-}" ]; then
  warn "systemd install skipped (CUTOFF_SKIP_SYSTEMD) — start with: $BIN_DIR/cutoff serve"
elif [ "$(id -u)" -ne 0 ]; then
  warn "systemd needs root — start with: $BIN_DIR/cutoff serve"
else
  warn "no systemd on this host — start with: $BIN_DIR/cutoff serve"
fi

echo
echo "CUTOFF $(cat "$PREFIX/VERSION") installed"
echo "  run it   : cutoff            (service)   |  cutoff serve  (foreground)"
echo "  open     : http://127.0.0.1:$PORT/"
echo "  token    : cutoff token"
echo "  uninstall: sudo cutoff uninstall"
